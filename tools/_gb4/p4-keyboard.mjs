/* P4 — KEYBOARD AND ASSISTIVE TECHNOLOGY on the pad, which is the
   population the new detail-0 listener exists to protect. Real key
   events go in through CDP; the detail-0 click is then generated by the
   browser itself, which is the only honest way to produce one. */
import { boot, instrument, arm, stop, padGeom, hand, toDoor, keyPress, reporter, verbList, count } from './lib.mjs';

const R = reporter();
const B = await boot();
const { page, cdp } = B;
await instrument(page);
const H = hand(cdp, page);
const closeAll = () => page.evaluate(() => WALLY.ctx.ui.closeAll());
const active = () => page.evaluate(() => {
  const a = document.activeElement;
  return a ? (a.tagName.toLowerCase() + (a.getAttribute && a.getAttribute('aria-label') ? '[' + a.getAttribute('aria-label') + ']' : '') + '.' + String(a.className || '').trim().split(/\s+/).join('.')) : 'null';
});
const focusAct = () => page.evaluate(() => { const b = document.querySelector('.w-abtn.act'); b.focus({ preventScroll: true }); return document.activeElement === b; });
const tab = async () => { await cdp.send('Input.dispatchKeyEvent', { type: 'rawKeyDown', windowsVirtualKeyCode: 9, key: 'Tab', code: 'Tab' }); await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', windowsVirtualKeyCode: 9, key: 'Tab', code: 'Tab' }); };

await toDoor(page); await closeAll(); await page.waitForTimeout(500);
const g = await padGeom(page);

/* ---- 0. can a Tab even reach the pad? ---- */
await page.evaluate(() => document.body.focus());
let reached = null;
for (let k = 0; k < 40 && !reached; k++) {
  await tab();
  const a = await active();
  if (a.includes('w-abtn')) reached = { k: k + 1, a };
}
R.ok(!!reached, 'P4-0 the pad is reachable with the Tab key', reached ? `after ${reached.k} tabs: ${reached.a}` : 'never reached in 40 tabs');

/* ---- 1. keyboard Enter on a live Enter button ---- */
await closeAll(); await page.waitForTimeout(400);
await toDoor(page); await page.waitForTimeout(400);
R.ok(await focusAct(), 'P4-1a the Enter button takes focus');
await arm(page);
await keyPress(cdp, 'Enter');
await page.waitForTimeout(900);
let r = await stop(page);
const kClick = r.log.filter(e => e.ty === 'click');
R.ok(count(r, 'interact') === 1 && r.panels.length === 1,
  'P4-1b a keyboard Enter on the focused pad button opens the door',
  `verbs ${verbList(r)} click ${JSON.stringify(kClick.map(c => [c.tgt, 'd' + c.detail]))} panels ${JSON.stringify(r.panels)}`);
await closeAll(); await page.waitForTimeout(400);

/* ---- 2. Space, the other activation key ---- */
await toDoor(page); await page.waitForTimeout(400);
await focusAct();
await arm(page);
await keyPress(cdp, ' ');
await page.waitForTimeout(900);
r = await stop(page);
R.ok(count(r, 'interact') === 1 && r.panels.length === 1,
  'P4-2 a keyboard Space on the focused pad button opens the door',
  `verbs ${verbList(r)} panels ${JSON.stringify(r.panels)}`);
await closeAll(); await page.waitForTimeout(400);

/* ---- 3. ...after a stray contact (the defect round three found) ---- */
await toDoor(page); await page.waitForTimeout(400);
await H.drag(200, 400, 120, 0, 8, 25);           // an ordinary camera drag
await page.waitForTimeout(300);
await focusAct();
await arm(page);
await keyPress(cdp, 'Enter');
await page.waitForTimeout(900);
r = await stop(page);
R.ok(count(r, 'interact') === 1 && r.panels.length === 1,
  'P4-3 a camera drag first does not eat the next keyboard activation',
  `verbs ${verbList(r)} panels ${JSON.stringify(r.panels)}`);
await closeAll(); await page.waitForTimeout(400);

/* ---- 4. ...after a MULTI-TOUCH pad press, which produces no compat
     click of its own and therefore leaves the swallow armed ---- */
await toDoor(page); await page.waitForTimeout(400);
await arm(page);
await H.down(1, 195, 300);                       // a finger parked on the canvas
await H.wait(100);
await H.down(2, g.act.cx, g.act.cy);             // Enter, two-fingered
await H.wait(150);
await H.up(2);
await H.wait(120);
await H.up(1);
await H.wait(700);
r = await stop(page);
const twoFingerClicks = r.log.filter(e => e.ty === 'click').length;
R.ok(count(r, 'interact') === 1, 'P4-4a the two-finger press fired', `verbs ${verbList(r)} clicks in sequence ${twoFingerClicks}`);
await closeAll(); await page.waitForTimeout(400);
await toDoor(page); await page.waitForTimeout(400);
await focusAct();
await arm(page);
await keyPress(cdp, 'Enter');
await page.waitForTimeout(900);
r = await stop(page);
R.ok(count(r, 'interact') === 1 && r.panels.length === 1,
  'P4-4b a keyboard activation straight after that two-finger press is NOT eaten by the armed swallow',
  `verbs ${verbList(r)} panels ${JSON.stringify(r.panels)}`);
await closeAll(); await page.waitForTimeout(400);

/* ---- 5. every button on the pad, from the keyboard ---- */
await toDoor(page); await page.waitForTimeout(400);
const each = [];
for (const label of ['Phone', 'Places', 'Desk', 'Menu']) {
  await page.evaluate((l) => {
    const b = [...document.querySelectorAll('.w-acts .w-abtn')].find((x) => x.getAttribute('aria-label') === l);
    b.focus({ preventScroll: true });
  }, label);
  await arm(page);
  await keyPress(cdp, 'Enter');
  await page.waitForTimeout(800);
  r = await stop(page);
  each.push(`${label}:${count(r, 'padpress')}/${JSON.stringify(r.panels)}`);
  await closeAll(); await page.waitForTimeout(400);
}
R.ok(each.every((s) => s.includes(':1/')), 'P4-5 every shortcut button answers a keyboard activation exactly once', each.join('  '));

/* ---- 6. the JUMP button from the keyboard ---- */
await page.evaluate((b) => { WALLY.ctx.ui.closeAll(); }, null);
await page.waitForTimeout(400);
await page.evaluate(() => document.querySelector('.w-abtn.jump').focus({ preventScroll: true }));
await arm(page);
await keyPress(cdp, 'Enter');
await page.waitForTimeout(900);
r = await stop(page);
R.ok(r.vy > 0.6, 'P4-6 a keyboard activation of Jump really jumps', `peak vy ${r.vy.toFixed(2)}, dy ${r.dy}`);

/* ---- 7. KEYBOARD WHILE THE CONTROLS ARE FADED ---- */
await toDoor(page); await closeAll();
await page.evaluate(() => { WALLY.debug.hideUI(true); WALLY.debug.idle(1.2); return null; });
await page.waitForTimeout(400);
await focusAct();
const focusBefore = await active();
await page.waitForTimeout(2600);                 // let it fade with focus on Enter
const idleNow = await page.evaluate(() => WALLY.debug.idle());
const focusAfter = await active();
await arm(page);
await keyPress(cdp, 'Enter');
await page.waitForTimeout(900);
r = await stop(page);
console.log(`   focus before the fade: ${focusBefore}\n   focus after the fade:  ${focusAfter}   idle ${JSON.stringify(idleNow)}`);
R.ok(idleNow.hidden === true, 'P4-7a the controls really were faded out', `hidden ${idleNow.hidden} live ${idleNow.live}`);
R.ok(count(r, 'padpress') === 0 && r.panels.length === 0,
  'P4-7b a keyboard Enter on a button that is faded out fires nothing',
  `focus ${focusAfter} verbs ${verbList(r) || 'none'} panels ${JSON.stringify(r.panels)}`);

/* ---- 8. can Tab REACH the pad while it is faded? ---- */
await page.evaluate(() => document.body.focus());
let reachedFaded = null;
for (let k = 0; k < 40 && !reachedFaded; k++) {
  await tab();
  const a = await active();
  if (a.includes('w-abtn')) reachedFaded = { k: k + 1, a };
}
const idle8 = await page.evaluate(() => WALLY.debug.idle());
R.ok(!reachedFaded && idle8.hidden,
  'P4-8 while faded, Tab cannot reach the pad at all (visibility:hidden takes it out of the tab order)',
  reachedFaded ? `reached ${reachedFaded.a} after ${reachedFaded.k} tabs, hidden ${idle8.hidden}` : `40 tabs, never reached; hidden ${idle8.hidden}`);

console.log(`\n${R.fails} failure(s). page errors: ${B.errs.length}`, B.errs.slice(0, 6).join(' | '));
await B.close();
